/**
 * Agriculture Training Institute - Reservation Form Templates Manager
 * Handles dynamic upload, preview, and reset of official forms for Facilities & Dorms
 */

function openManageFormTemplatesModal() {
  const modal = document.getElementById('manageFormTemplatesModal');
  if (modal) {
    modal.style.display = 'flex';
    document.body.style.overflow = 'hidden';
    loadFormTemplates();
  }
}

function closeManageFormTemplatesModal() {
  const modal = document.getElementById('manageFormTemplatesModal');
  if (modal) {
    modal.style.display = 'none';
    document.body.style.overflow = '';
  }
}

// Close on backdrop click
document.addEventListener('click', function (e) {
  const modal = document.getElementById('manageFormTemplatesModal');
  if (modal && e.target === modal) {
    closeManageFormTemplatesModal();
  }
});

// Close on ESC key
document.addEventListener('keydown', function (e) {
  if (e.key === 'Escape') {
    closeManageFormTemplatesModal();
  }
});

/**
 * Fetch and display current form template details from backend
 */
function loadFormTemplates() {
  fetch('ajax/template_actions.php?action=get_templates')
    .then(res => res.json())
    .then(data => {
      if (data.success && data.templates) {
        renderTemplateCard('facility', data.templates.facility);
        renderTemplateCard('dormitory', data.templates.dormitory);
      }
    })
    .catch(err => {
      console.error('Error fetching template status:', err);
    });
}

function renderTemplateCard(type, info) {
  const isFacility = (type === 'facility');
  const pfx = isFacility ? 'Facility' : 'Dormitory';

  const badgeEl = document.getElementById(`badge${pfx}Status`);
  const fileNameEl = document.getElementById(`txt${pfx}FileName`);
  const metaEl = document.getElementById(`txt${pfx}Meta`);
  const resetBtn = document.getElementById(`btn${pfx}Reset`);
  const downloadBtn = document.getElementById(`btn${pfx}Download`);
  const dropTxt = document.getElementById(`dropTxt${pfx}`);
  const submitWrap = document.getElementById(`submitWrap${pfx}`);
  const fileInput = document.getElementById(`input${pfx}File`);

  if (!badgeEl || !fileNameEl || !metaEl) return;

  // Clear pending upload state
  if (fileInput) fileInput.value = '';
  if (submitWrap) submitWrap.style.display = 'none';
  if (dropTxt) dropTxt.innerHTML = 'Click or drag new official file here';

  if (info && info.is_custom) {
    // Custom Uploaded Form is Active
    badgeEl.style.background = '#dcfce7';
    badgeEl.style.color = '#15803d';
    badgeEl.style.border = '1px solid #bbf7d0';
    badgeEl.innerHTML = '🟢 Custom Upload Active';

    fileNameEl.textContent = info.file_name || 'Official Form Template';
    fileNameEl.title = info.file_name || '';

    const uploadedDate = info.uploaded_at_formatted || 'Recently';
    const uploadedBy = info.uploaded_by_name || 'Administrator';
    const size = info.file_size_formatted || '';
    metaEl.textContent = `${size ? size + ' • ' : ''}Uploaded on ${uploadedDate} by ${uploadedBy}`;

    if (resetBtn) resetBtn.style.display = 'inline-flex';
    if (downloadBtn) {
      downloadBtn.href = info.download_url || (isFacility ? 'download_form.php' : 'download_dormitory_form.php');
      downloadBtn.innerHTML = `
        <svg width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.4"><path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"></path><polyline points="7 10 12 15 17 10"></polyline><line x1="12" y1="15" x2="12" y2="3"></line></svg>
        <span>Download Active File</span>
      `;
    }
  } else {
    // Default System Printable Template
    badgeEl.style.background = '#f1f5f9';
    badgeEl.style.color = '#475569';
    badgeEl.style.border = '1px solid #e2e8f0';
    badgeEl.innerHTML = '⚪ System Default Form';

    fileNameEl.textContent = isFacility 
      ? 'Official ATI Facility Reservation Form & Terms'
      : 'Official ATI Dormitory Reservation Form (ATI-QF/DTS-22)';

    metaEl.textContent = 'Default dynamic printable slip generated by system';

    if (resetBtn) resetBtn.style.display = 'none';
    if (downloadBtn) {
      downloadBtn.href = isFacility ? 'download_form.php?mode=html' : 'download_dormitory_form.php?mode=html';
      downloadBtn.innerHTML = `
        <svg width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.4"><path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"></path><polyline points="7 10 12 15 17 10"></polyline><line x1="12" y1="15" x2="12" y2="3"></line></svg>
        <span>Preview Default Slip</span>
      `;
    }
  }
}

/**
 * Handle file input selection and preview
 */
function onFileSelected(input, type) {
  const pfx = (type === 'facility') ? 'Facility' : 'Dormitory';
  const dropTxt = document.getElementById(`dropTxt${pfx}`);
  const submitWrap = document.getElementById(`submitWrap${pfx}`);

  if (input.files && input.files[0]) {
    const file = input.files[0];
    const sizeKB = (file.size / 1024).toFixed(1);
    const sizeStr = (sizeKB > 1024) ? (sizeKB / 1024).toFixed(2) + ' MB' : sizeKB + ' KB';

    if (dropTxt) {
      dropTxt.innerHTML = `
        <span style="color: #0f172a; font-weight: 700;">Selected:</span> ${escapeHtml(file.name)} 
        <span style="color: #64748b; font-size: 0.74rem;">(${sizeStr})</span>
      `;
    }
    if (submitWrap) submitWrap.style.display = 'block';
  } else {
    if (dropTxt) dropTxt.innerHTML = 'Click or drag new official file here';
    if (submitWrap) submitWrap.style.display = 'none';
  }
}

/**
 * Upload official template form via AJAX
 */
function handleUploadTemplate(e, type) {
  e.preventDefault();
  const pfx = (type === 'facility') ? 'Facility' : 'Dormitory';
  const fileInput = document.getElementById(`input${pfx}File`);
  const submitBtn = document.getElementById(`btnSubmit${pfx}`);

  if (!fileInput || !fileInput.files || !fileInput.files[0]) {
    if (typeof showAdminToast === 'function') {
      showAdminToast('Please select a PDF or DOCX file to upload.', 'decline');
    } else {
      alert('Please select a file.');
    }
    return;
  }

  const file = fileInput.files[0];
  const formData = new FormData();
  formData.append('action', 'upload_template');
  formData.append('type', type);
  formData.append('template_file', file);

  const origBtnHtml = submitBtn ? submitBtn.innerHTML : '';
  if (submitBtn) {
    submitBtn.disabled = true;
    submitBtn.innerHTML = `
      <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" style="animation: spin 1s linear infinite;"><path d="M21 12a9 9 0 1 1-6.219-8.56"/></svg>
      <span>Uploading &amp; Applying Template...</span>
    `;
  }

  fetch('ajax/template_actions.php', {
    method: 'POST',
    body: formData
  })
    .then(res => res.json())
    .then(data => {
      if (submitBtn) {
        submitBtn.disabled = false;
        submitBtn.innerHTML = origBtnHtml;
      }

      if (data.success) {
        if (typeof showAdminToast === 'function') {
          showAdminToast(data.message || 'Official template updated successfully!', 'success');
        } else {
          alert(data.message || 'Template updated successfully!');
        }

        renderTemplateCard(type, data.template);
      } else {
        if (typeof showAdminToast === 'function') {
          showAdminToast(data.message || 'Failed to upload template.', 'decline');
        } else {
          alert(data.message || 'Upload error');
        }
      }
    })
    .catch(err => {
      console.error(err);
      if (submitBtn) {
        submitBtn.disabled = false;
        submitBtn.innerHTML = origBtnHtml;
      }
      if (typeof showAdminToast === 'function') {
        showAdminToast('Network error while uploading form template. Please try again.', 'decline');
      } else {
        alert('Network error while uploading.');
      }
    });
}

/**
 * Reset template to system default printable form
 */
function confirmResetTemplate(type) {
  const typeName = (type === 'facility') ? 'Facility' : 'Dormitory';
  const msg = `Are you sure you want to reset the Official ATI ${typeName} Reservation Form to the system default printable template?`;

  if (!confirm(msg)) return;

  const formData = new FormData();
  formData.append('action', 'reset_template');
  formData.append('type', type);

  fetch('ajax/template_actions.php', {
    method: 'POST',
    body: formData
  })
    .then(res => res.json())
    .then(data => {
      if (data.success) {
        if (typeof showAdminToast === 'function') {
          showAdminToast(data.message || `Reset ${typeName} form to default.`, 'success');
        } else {
          alert(data.message || 'Reset successfully.');
        }

        renderTemplateCard(type, data.template);
      } else {
        if (typeof showAdminToast === 'function') {
          showAdminToast(data.message || 'Failed to reset template.', 'decline');
        } else {
          alert(data.message || 'Reset failed.');
        }
      }
    })
    .catch(err => {
      console.error(err);
      if (typeof showAdminToast === 'function') {
        showAdminToast('Network error while resetting template.', 'decline');
      }
    });
}

/**
 * Initialize Drag & Drop for a dropzone
 */
function initDropZone(dropZoneId, inputId, type) {
  const dropZone = document.getElementById(dropZoneId);
  const input = document.getElementById(inputId);
  if (!dropZone || !input) return;

  ['dragenter', 'dragover'].forEach(eventName => {
    dropZone.addEventListener(eventName, function (e) {
      e.preventDefault();
      e.stopPropagation();
      dropZone.style.borderColor = '#0284c7';
      dropZone.style.background = '#e0f2fe';
    }, false);
  });

  ['dragleave', 'drop'].forEach(eventName => {
    dropZone.addEventListener(eventName, function (e) {
      e.preventDefault();
      e.stopPropagation();
      dropZone.style.borderColor = '';
      dropZone.style.background = '';
    }, false);
  });

  dropZone.addEventListener('drop', function (e) {
    const dt = e.dataTransfer;
    if (dt && dt.files && dt.files.length) {
      input.files = dt.files;
      onFileSelected(input, type);
    }
  }, false);
}

document.addEventListener('DOMContentLoaded', function () {
  initDropZone('dropZoneFacility', 'inputFacilityFile', 'facility');
  initDropZone('dropZoneDormitory', 'inputDormitoryFile', 'dormitory');
});

// Helper
function escapeHtml(text) {
  if (!text) return '';
  const map = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;' };
  return String(text).replace(/[&<>"']/g, m => map[m]);
}
